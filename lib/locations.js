export const formatLocationSlug = (slug) => {
  return slug
    .split('-')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
};

export const getLocationBySlug = (slug) => {
  return SERVICE_LOCATIONS.find(l => l.slug === slug);
};

// True only when a dedicated /locations/{area}/{service} page is actually built.
export const hasIntersectionPage = (areaSlug, serviceSlug) =>
  CORE_SERVICE_AREAS.includes(areaSlug) && INTERSECTION_SERVICES.includes(serviceSlug);
